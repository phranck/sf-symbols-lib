/**
 * Generate main index.ts that re-exports dualtone as the default variant
 */
function generateMainIndex(srcDir: string): void {
  const fileContent = `/**
 * ╔══════════════════════════════════════════════════════════╗
 * ║       AUTO-GENERATED FILE - DO NOT EDIT MANUALLY         ║
 * ╚══════════════════════════════════════════════════════════╝
 *
 * SF Symbols Library
 *
 * The default export re-exports the dualtone variant.
 * For a specific variant, import directly:
 *   import { SFCheckmarkCircle } from 'sf-symbols-lib/dualtone';
 *   import { SFCheckmarkCircle } from 'sf-symbols-lib/monochrome';
 *
 * Generated by: scripts/generate-sfsymbols.ts
 */

// Re-export dualtone as default variant
export * from './dualtone';
`;

  fs.writeFileSync(path.join(srcDir, 'index.ts'), fileContent);
  console.log('✅ CREATED: index.ts (default: dualtone)');
}

// ---------------------------------------------------------------------------
// README / package.json updates
// ---------------------------------------------------------------------------

/** Update the SF Symbols count badge and text in README.md */
function updateReadmeSymbolCount(symbolCount: number): void {
  const readmePath = path.join(process.cwd(), 'README.md');
  if (!fs.existsSync(readmePath)) return;

  let content = fs.readFileSync(readmePath, 'utf-8');
  const formatted = symbolCount.toLocaleString();

  const badgeUrl = `https://img.shields.io/badge/SF%20Symbols-${symbolCount}-blue?style=flat-square&logo=apple&logoColor=white`;
  content = content.replace(
    /!\[SF Symbols\]\([^)]+\)/,
    `![SF Symbols](${badgeUrl})`,
  );
  content = content.replace(
    /A React component library providing \*\*[\d,]+\s+SF Symbols\*\*/,
    `A React component library providing **${formatted} SF Symbols**`,
  );
  content = content.replace(
    /^- \*\*[\d,]+\s+Symbols\*\*/m,
    `- **${formatted} Symbols**`,
  );

  fs.writeFileSync(readmePath, content);
  console.log(`✅ UPDATED: README.md with ${symbolCount} symbols`);
}

/** Update the symbol count in package.json description */
function updatePackageJsonSymbolCount(symbolCount: number): void {
  const pkgPath = path.join(process.cwd(), 'package.json');
  if (!fs.existsSync(pkgPath)) return;

  const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8'));
  if (pkg.description) {
    pkg.description = pkg.description.replace(
      /SF Symbols \([\d,]+\)/,
      `SF Symbols (${symbolCount.toLocaleString()})`,
    );
  }

  fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
  console.log(
    `✅ UPDATED: package.json description with ${symbolCount} symbols`,
  );
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

async function generateSFSymbols() {
  const svgsDir = path.join(process.cwd(), '.svgs');
  const srcDir = path.join(process.cwd(), 'src');

  const dualtoneDir = path.join(svgsDir, 'dualtone');
  if (!fs.existsSync(dualtoneDir)) {
    console.error(
      `❌ ERROR: Expected directory structure not found: ${dualtoneDir}`,
    );
    process.exit(1);
  }

  const symbolFileNames = fs
    .readdirSync(dualtoneDir)
    .filter((file) => file.endsWith('.svg'))
    .map((file) => file.replace('.svg', ''));

  if (symbolFileNames.length === 0) {
    console.error('❌ No SVG files found.');
    process.exit(1);
  }

  console.log(`\n🔍 Found ${symbolFileNames.length} symbols\n`);

  // Step 1: Process each variant - generate individual icon components
  let totalProcessed = 0;

  for (const variant of VARIANTS) {
    const variantSvgDir = path.join(svgsDir, variant);
    if (!fs.existsSync(variantSvgDir)) {
      console.warn(`⚠️  Directory not found: ${variantSvgDir}`);
      continue;
    }

    const pascalNames: string[] = [];
    let variantCount = 0;

    for (const fileName of symbolFileNames) {
      const svgPath = path.join(variantSvgDir, `${fileName}.svg`);
      if (!fs.existsSync(svgPath)) continue;

      const pascalName = kebabToPascalCase(fileName);

      try {
        const entry = parseSvgFile(svgPath);

        // Cross-validate lib name
        if (
          entry.metadata?.libName &&
          entry.metadata.libName !== pascalName
        ) {
          console.warn(
            `⚠️  Name mismatch for ${fileName}: embedded="${entry.metadata.libName}" vs generated="${pascalName}"`,
          );
        }

        generateIconComponentFile(srcDir, variant, pascalName, entry);
        pascalNames.push(pascalName);
        variantCount++;
        totalProcessed++;
      } catch (error) {
        console.error(
          `❌ ERROR processing ${svgPath}:`,
          error instanceof Error ? error.message : error,
        );
      }
    }

    // Generate barrel export
    generateBarrelExport(srcDir, variant, pascalNames);
    console.log(`✓ ${variant}: ${variantCount} icons`);
  }

  // Step 2: Generate main index.ts (re-exports dualtone)
  generateMainIndex(srcDir);

  // Step 3: Update README and package.json
  updateReadmeSymbolCount(symbolFileNames.length);
  updatePackageJsonSymbolCount(symbolFileNames.length);

  // Step 4: Generate docs data
  console.log('\n📄 Generating docs data and preview page...');
  execSync('tsx ./scripts/generate-docs-data.ts', { stdio: 'inherit' });

  console.log(
    `\n📊 Summary: ${symbolFileNames.length} symbols x ${VARIANTS.length} variants = ${totalProcessed} individual icon components\n`,
  );
}

generateSFSymbols().catch((error) => {
  console.error('❌ Error generating SF Symbols:', error);
  process.exit(1);
});
